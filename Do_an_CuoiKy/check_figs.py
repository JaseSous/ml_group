import os, json, re

all_notebooks = []
for root, dirs, files in os.walk('Do_an_CuoiKy'):
    for f in files:
        if f.endswith('.ipynb'):
            all_notebooks.append(os.path.join(root, f))

print(f"Total notebooks found: {len(all_notebooks)}")

fig_map = {}
for nb_path in sorted(all_notebooks):
    try:
        with open(nb_path, 'r', encoding='utf-8') as f:
            nb = json.load(f)
        for i, cell in enumerate(nb.get('cells', [])):
            src = ''.join(cell.get('source', []))
            for line in src.split('\n'):
                if 'savefig' in line or '.png' in line:
                    m = re.findall(r'[\w\-]+\.png', line)
                    for fn in m:
                        rel = os.path.relpath(nb_path, 'Do_an_CuoiKy')
                        fig_map.setdefault(fn, set()).add(rel)
    except Exception as e:
        print(f"Error reading {nb_path}: {e}")

print("\n--- FIGURES GENERATED BY NOTEBOOKS ---")
for fn in sorted(fig_map.keys()):
    print(f"{fn} -> {', '.join(sorted(fig_map[fn]))}")
